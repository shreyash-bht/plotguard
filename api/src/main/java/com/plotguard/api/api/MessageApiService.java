package com.plotguard.api.api;

import com.plotguard.api.dto.NewMessageDto;
import com.plotguard.api.entity.Conversation;
import com.plotguard.api.entity.Message;
import com.plotguard.api.entity.MessageRole;
import com.plotguard.api.repository.ConversationRepository;
import com.plotguard.api.repository.MessageRepository;
import jakarta.persistence.EntityNotFoundException;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import javax.naming.directory.InvalidAttributesException;
import java.util.List;
import java.util.UUID;

@Service
public class MessageApiService {
    @Autowired
    private MessageRepository messageRepository;

    @Autowired
    private ConversationRepository conversationRepository;

    public List<Message> getAllMessages(UUID conversationId, UUID userId) {
        getConversationForUser(conversationId, userId);
        return messageRepository.findAllByConversationIdOrderByCreatedAtAsc(conversationId);
    }

    @Transactional
    public Message addMessageToConversation(UUID conversationId, NewMessageDto newMessageDto) throws InvalidAttributesException {
        if(newMessageDto.getMessageId() != null)
            throw new InvalidAttributesException("Message ID must not be provided; it is generated by the database");
        if(newMessageDto.getConversationId() != null && ! conversationId.equals(newMessageDto.getConversationId()))
            throw new InvalidAttributesException("Conversation IDs don't match");
        getConversationForUser(conversationId, newMessageDto.getUserId());
        Message newMessage = Message.builder()
                .conversationId(conversationId)
                .role(newMessageDto.getRole() == null ? MessageRole.USER : newMessageDto.getRole())
                .originalContent(newMessageDto.getOriginalContent())
                .contextualizedContent(newMessageDto.getContextualizedContent())
                .build();
        return messageRepository.save(newMessage);
    }

    private Conversation getConversationForUser(UUID conversationId, UUID userId) {
        return conversationRepository.findByConversationIdAndUserId(conversationId, userId)
                .orElseThrow(() -> new EntityNotFoundException("Conversation with given ID and user does not exist"));
    }
}
