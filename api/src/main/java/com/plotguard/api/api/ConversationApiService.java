package com.plotguard.api.api;

import com.plotguard.api.dto.NewConversationDto;
import com.plotguard.api.dto.UpdateConversationDto;
import com.plotguard.api.entity.Conversation;
import com.plotguard.api.repository.ContentRepository;
import com.plotguard.api.repository.ConversationRepository;
import com.plotguard.api.repository.UserRepository;
import jakarta.persistence.EntityNotFoundException;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import javax.naming.directory.InvalidAttributesException;
import java.util.List;
import java.util.UUID;

@Service
public class ConversationApiService {
    @Autowired
    private ConversationRepository conversationRepository;

    @Autowired
    private UserRepository userRepository;

    @Autowired
    private ContentRepository contentRepository;

    @Transactional
    public Conversation createConversation(NewConversationDto newConversationDto) throws InvalidAttributesException {
        if(newConversationDto.getConversationId() != null)
            throw new InvalidAttributesException("Conversation ID must not be provided; it is generated by the database");
        if(! userRepository.existsById(newConversationDto.getUserId()))
            throw new EntityNotFoundException("User with given ID does not exist");
        if(! contentRepository.existsById(newConversationDto.getContentId()))
            throw new EntityNotFoundException("Content with given ID does not exist");
        Conversation newConversation = Conversation.builder()
                .userId(newConversationDto.getUserId())
                .contentId(newConversationDto.getContentId())
                .maxStoryOrder(newConversationDto.getMaxStoryOrder())
                .build();
        return conversationRepository.save(newConversation);
    }

    public List<Conversation> getConversationsByUser(UUID userId) {
        return conversationRepository.findAllByUserIdOrderByUpdatedAtDesc(userId);
    }

    public Conversation getConversation(UUID conversationId) {
        return conversationRepository.findById(conversationId)
                .orElseThrow(() -> new EntityNotFoundException("Conversation with given ID does not exist"));
    }

    @Transactional
    public Conversation updateConversation(UUID conversationId, UpdateConversationDto updateConversationDto) throws InvalidAttributesException {
        Conversation conversation = conversationRepository.findByConversationIdAndUserId(
                        conversationId, updateConversationDto.getUserId())
                .orElseThrow(() -> new EntityNotFoundException("Conversation with given ID and user does not exist"));
        conversation.setMaxStoryOrder(updateConversationDto.getMaxStoryOrder());
        return conversationRepository.save(conversation);
    }
}
